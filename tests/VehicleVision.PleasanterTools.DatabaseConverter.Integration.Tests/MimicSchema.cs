    /// <summary>日本語・サロゲートペア（絵文字）・改行・タブを混ぜた長い文字列。</summary>
    public static string LongText(int length)
    {
        const string unit = "日本語のテキスト😀 ASCII text.\r\n\t行末 ";
        var sb = new StringBuilder(length + unit.Length);
        while (sb.Length < length)
        {
            sb.Append(unit);
        }

        // サロゲートペアを分断しない位置で切る
        var cut = length;
        if (char.IsHighSurrogate(sb[cut - 1]))
        {
            cut--;
        }

        return sb.ToString(0, cut);
    }

    /// <summary>Items 25 行。投入後に最後の行（25）を消し、自動採番を「最大値 + 1」より進める。</summary>
    public static IEnumerable<object?[]> ItemRows()
    {
        for (var i = 1; i <= 25; i++)
        {
            var title = i switch
            {
                1 => "日本語のタイトル",
                2 => "😀 emoji タイトル 😀",
                3 => "末尾空白  ",
                4 => string.Empty,
                5 => null,
                6 => new string('漢', 700),
                _ => $"Title {i}",
            };
            var fullText = i switch
            {
                7 => LongText(200_000),
                8 => null,
                9 => "line1\r\nline2\ttab　全角空白",
                _ => $"full text {i}",
            };
            var created = i switch
            {
                10 => new DateTime(1753, 1, 1),
                11 => new DateTime(1900, 1, 1),
                12 => new DateTime(9999, 12, 31, 23, 59, 59, 997),
                13 => new DateTime(2024, 2, 29, 12, 34, 56, 123),
                14 => new DateTime(2024, 1, 1, 0, 0, 0, 3),
                _ => new DateTime(2024, 1, 1).AddMinutes(i),
            };
            decimal? weight = i switch
            {
                1 => 123456789012345.1234m,
                2 => -0.0001m,
                3 => 0m,
                4 => null,
                _ => i * 1.5m,
            };
            double? ratio = i switch
            {
                1 => 0.1,
                2 => 1e-10,
                3 => 12345.6789,
                4 => null,
                _ => i / 7.0,
            };
            yield return new object?[]
            {
                i % 3 == 0 ? "Wikis" : "Results",
                100L + (i % 4),
                title,
                fullText,
                i % 2 == 0,
                weight,
                ratio,
                created,
                i % 3 == 0 ? null : created.AddSeconds(5),
            };
        }
    }

