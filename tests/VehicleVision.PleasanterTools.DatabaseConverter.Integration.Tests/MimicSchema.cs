/// <summary>テスト用の列（投入と比較に使う）。</summary>
internal sealed record MimicColumn(string Name, ColumnType Type, bool Generated = false)
{
    /// <summary>投入のパラメータの型。SQL Server の datetime だけ、方言ごとに違う。</summary>
    public ColumnType TypeFor(Dbms dbms)
        => Type.Kind == ValueKind.DateTime && dbms == Dbms.SqlServer
            ? Type with { IsLegacyDateTime = true, NativeName = "datetime" }
            : Type;
}

