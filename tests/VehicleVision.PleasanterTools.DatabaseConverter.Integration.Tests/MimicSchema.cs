    public static IEnumerable<object?[]> BinaryRows()
    {
        var all = new byte[256];
        for (var i = 0; i < all.Length; i++)
        {
            all[i] = (byte)i;
        }

        var seventy = new byte[70_000]; // MySQL の blob（64KB）を超える
        var large = new byte[3 * 1024 * 1024]; // バッチのバイト数の上限（既定 4MiB）を使い切る大きさ
        var random = new Random(12345);
        random.NextBytes(seventy);
        random.NextBytes(large);

        var bins = new byte[]?[] { [], [0x00], all, seventy, large, null };
        for (var i = 0; i < bins.Length; i++)
        {
            yield return new object?[]
            {
                1L,
                (long)(i + 1),
                i % 2 == 0 ? "Attachments" : "Images",
                i == 3 ? "バイナリ😀" : $"file{i}.bin",
                bins[i],
                i % 2 == 0 ? new byte[] { 1, 2, 3 } : null,
                "application/octet-stream",
                new DateTime(2024, 4, 1).AddMinutes(i),
            };
        }
    }
